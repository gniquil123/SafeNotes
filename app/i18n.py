def set_language(code: str) -> None:
    _ctx["lang"] = code if code in _TR else _DEFAULT


def language() -> str:
    return _ctx["lang"]


def tr(s: str) -> str:
    """把中文源串翻译为当前语言的文本；zh 直接返回原串。"""
    lang = _ctx["lang"]
    if lang == _DEFAULT:
        return s
    return _TR.get(lang, {}).get(s, s)


def tf(s: str, **kw) -> str:
    """翻译模板串并填充命名占位符 {name}。"""
    out = tr(s)
    try:
        return out.format(**kw)
    except (KeyError, IndexError, ValueError):
        return out